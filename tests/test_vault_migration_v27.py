"""FEAT-67 phase A: schema v27 (vault support missions) upgrades a v26 file in place, decision D43. Written before the implementation.

CONTRACT: user_version becomes 27; a v26 file is backed up first as ``<file>.pre-v27-<ns>.sqlite3`` (label = the version being upgraded TO,
as v26 used ``pre-v26`` for a v25 file); everything is additive and idempotent: ``CREATE TABLE IF NOT EXISTS`` for ``vault_support_missions``
and ``vault_support_attempts`` and one ``ALTER TABLE vault_operation_settings ADD COLUMN support_reward INTEGER NOT NULL DEFAULT 0`` that is
skipped when the column exists. ``vault_operation_claims`` is NOT altered (its type column has no CHECK; "support" is just a new value).
A fresh store and an upgraded file have the same schema, and both equal tests/fixtures/schema_pin.json (regenerated by the implementer, including
the legacy v5 entry). Table details: tests/test_vault_missions_store.py.
"""
import json
import sqlite3
import tempfile
import unittest
from contextlib import closing
from pathlib import Path
from unittest import mock

from llmcord_core.store import Store

G, CH, ALICE = 1, 100, 5
NOW = 1_760_529_600.0
SUPPORT_TABLES = ("vault_support_attempts", "vault_support_missions")
OPERATION_TABLES = ("vault_operation_claims", "vault_operation_clues", "vault_operation_actions", "vault_operation_stages",
                    "vault_operation_participants", "vault_operations", "vault_operation_settings")
VAULT_TABLES = ("vault_reward_claims", "vault_actions", "vault_clues", "vault_stages", "vault_sessions", "vault_settings", "vault_advice", "vault_tool_uses")


def tables(path):
    with closing(sqlite3.connect(path)) as db:
        return {r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}


def columns(path, table):
    with closing(sqlite3.connect(path)) as db:
        return [r[1] for r in db.execute(f"PRAGMA table_info({table})")]


def schema(path):
    with closing(sqlite3.connect(path)) as db:
        return sorted(r[0] for r in db.execute("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL"))


def version(path):
    with closing(sqlite3.connect(path)) as db:
        return db.execute("PRAGMA user_version").fetchone()[0]


def v26_file(folder):
    """A current store with the v27 additions removed again and user_version set back to 26, holding a balance, a settings row,
    a joined operation and one paid contribution claim."""
    path = Path(folder) / "v26.sqlite3"
    store = Store(path)
    w = store.create_space(G, "W", "world")
    a, b = store.create_character(G, w, "Ann"), store.create_character(G, w, "Bea")
    store.bind_channel(G, CH, w)
    store.set_cast(CH, None, [a, b])
    store.change_balance(G, ALICE, 120, "start", 1)
    store.set_vault_settings(G, enabled=True)
    store.set_vault_operation_settings(G, enabled=True, channel_id=CH, contribution_reward=20, team_reward=50, min_guesses=2)
    view = store.open_vault_operation(G, ALICE, CH, now=NOW, seed="v26")
    secret = store.one("SELECT secret FROM vault_operation_stages WHERE operation_id=?", (view["id"],))["secret"]
    wrong = next(c for c in ("0123", "1234", "2345") if c != secret)
    store.submit_operation_guess(G, ALICE, view["id"], wrong, now=NOW)
    store.close()
    with closing(sqlite3.connect(path)) as db, db:
        for table in SUPPORT_TABLES:
            db.execute(f"DROP TABLE IF EXISTS {table}")
        if "support_reward" in [r[1] for r in db.execute("PRAGMA table_info(vault_operation_settings)")]:
            db.execute("ALTER TABLE vault_operation_settings DROP COLUMN support_reward")
        db.execute("PRAGMA user_version=26")
    return path, view["id"]


class V26UpgradeTests(unittest.TestCase):
    def test_upgrade_adds_the_tables_and_column_with_a_pre_v27_backup_and_keeps_rows(self):
        with tempfile.TemporaryDirectory() as folder:
            path, oid = v26_file(folder)
            self.assertFalse(set(SUPPORT_TABLES) & tables(path))
            self.assertNotIn("support_reward", columns(path, "vault_operation_settings"))
            store = Store(path)
            try:
                self.assertEqual(store.one("PRAGMA user_version")[0], 27)
                self.assertEqual(store.balance(G, ALICE), 120)   # min_guesses=2: the one guess has not paid yet
                settings = store.vault_operation_settings(G)
                self.assertEqual((settings["enabled"], settings["channel_id"], settings["contribution_reward"], settings["team_reward"], settings["min_guesses"]),
                                 (True, CH, 20, 50, 2))
                self.assertEqual(settings["support_reward"], 0)
                self.assertEqual(store.vault_operation(G, ALICE, oid, now=NOW)["participants"][0]["contributions"], 1)
                self.assertEqual(store.all("SELECT 1 FROM vault_support_missions"), [])
                self.assertEqual(store.all("SELECT 1 FROM vault_support_attempts"), [])
            finally:
                store.close()
            self.assertTrue(set(SUPPORT_TABLES) <= tables(path))
            self.assertIn("support_reward", columns(path, "vault_operation_settings"))
            backups = list(Path(folder).glob("v26.sqlite3.pre-v27-*.sqlite3"))
            self.assertEqual(len(backups), 1)
            self.assertEqual(version(backups[0]), 26)
            self.assertFalse(set(SUPPORT_TABLES) & tables(backups[0]))
            self.assertNotIn("support_reward", columns(backups[0], "vault_operation_settings"))

    def test_the_claims_table_is_not_altered(self):
        with tempfile.TemporaryDirectory() as folder:
            path, _ = v26_file(folder)
            before = [s for s in schema(path) if "vault_operation_claims" in s]
            Store(path).close()
            self.assertEqual([s for s in schema(path) if "vault_operation_claims" in s], before)

    def test_a_missions_reward_can_be_claimed_in_an_upgraded_file(self):
        """The existing claims table takes a 'support' row (no CHECK to widen), unique per operation and member."""
        with tempfile.TemporaryDirectory() as folder:
            path, oid = v26_file(folder)
            store = Store(path)
            try:
                entry = store.one("SELECT id FROM currency_ledger WHERE guild_id=? ORDER BY id DESC LIMIT 1", (G,))
                store.db.execute("INSERT INTO vault_operation_claims(guild_id,operation_id,user_id,type,amount,ledger_id,created_at) VALUES(?,?,?,?,?,?,?)",
                                 (G, oid, ALICE, "support", 15, entry["id"], NOW))
                with self.assertRaises(sqlite3.IntegrityError):
                    store.db.execute("INSERT INTO vault_operation_claims(guild_id,operation_id,user_id,type,amount,ledger_id,created_at) VALUES(?,?,?,?,?,?,?)",
                                     (G, oid, ALICE, "support", 15, entry["id"], NOW))
                store.db.rollback()
            finally:
                store.close()

    def test_upgrade_is_idempotent_and_makes_one_backup(self):
        with tempfile.TemporaryDirectory() as folder:
            path, _ = v26_file(folder)
            Store(path).close()
            first = schema(path)
            Store(path).close()
            self.assertEqual(schema(path), first)
            self.assertEqual(len(list(Path(folder).glob("*.pre-v27-*.sqlite3"))), 1)
            self.assertEqual(columns(path, "vault_operation_settings").count("support_reward"), 1)

    def test_a_file_that_already_has_the_column_still_upgrades(self):
        """The ALTER is guarded: a v26 file whose settings table already holds support_reward (an interrupted manual step) is not an error."""
        with tempfile.TemporaryDirectory() as folder:
            path, _ = v26_file(folder)
            with closing(sqlite3.connect(path)) as db, db:
                db.execute("ALTER TABLE vault_operation_settings ADD COLUMN support_reward INTEGER NOT NULL DEFAULT 0")
            Store(path).close()
            self.assertEqual(version(path), 27)
            self.assertEqual(columns(path, "vault_operation_settings").count("support_reward"), 1)

    def test_a_current_file_is_not_backed_up_again(self):
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "now.sqlite3"
            Store(path).close()
            Store(path).close()
            self.assertEqual(list(Path(folder).glob("*.pre-*.sqlite3")), [])

    def test_older_files_still_get_one_backup_labelled_for_their_own_step(self):
        """A v24 file is backed up once, before anything changes, and still ends at v27 (the old label is not rewritten)."""
        with tempfile.TemporaryDirectory() as folder:
            path, _ = v26_file(folder)
            with closing(sqlite3.connect(path)) as db, db:
                for table in (*OPERATION_TABLES, *VAULT_TABLES):
                    db.execute(f"DROP TABLE IF EXISTS {table}")
                db.execute("PRAGMA user_version=24")
            Store(path).close()
            backups = list(Path(folder).glob("*.pre-*.sqlite3"))
            self.assertEqual(len(backups), 1)
            self.assertIn(".pre-v25-", backups[0].name)
            self.assertEqual(version(path), 27)
            self.assertTrue(set(SUPPORT_TABLES) <= tables(path))

    def test_a_failed_upgrade_leaves_the_v26_file_as_it_was(self):
        """The upgrade is one transaction: a statement that fails halfway rolls the whole upgrade back (the existing atomic-upgrade guarantee)."""
        with tempfile.TemporaryDirectory() as folder:
            path, _ = v26_file(folder)
            before = schema(path)
            with mock.patch.object(Store, "migrate_admin", side_effect=RuntimeError("boom")), self.assertRaises(RuntimeError):
                Store(path)
            self.assertEqual(version(path), 26)
            self.assertEqual(schema(path), before)

    def test_a_newer_file_is_still_refused(self):
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "new.sqlite3"
            with closing(sqlite3.connect(path)) as db, db:
                db.execute("PRAGMA user_version=28")
            with self.assertRaisesRegex(ValueError, "newer than this application"):
                Store(path)
            self.assertEqual(list(Path(folder).glob("*.pre-*.sqlite3")), [])


class SchemaTests(unittest.TestCase):
    def test_fresh_store_is_v27_with_the_support_tables_and_column(self):
        store = Store()
        self.addCleanup(store.close)
        self.assertEqual(store.one("PRAGMA user_version")[0], 27)
        have = {r[0] for r in store.all("SELECT name FROM sqlite_master WHERE type='table'")}
        self.assertTrue(set(SUPPORT_TABLES) <= have)
        self.assertIn("support_reward", {r[1] for r in store.all("PRAGMA table_info(vault_operation_settings)")})

    def test_upgraded_file_has_the_fresh_schema(self):
        with tempfile.TemporaryDirectory() as folder:
            path, _ = v26_file(folder)
            Store(path).close()
            fresh = Path(folder) / "fresh.sqlite3"
            Store(fresh).close()
            self.assertEqual(schema(path), schema(fresh))

    def test_fresh_schema_equals_the_pin(self):
        """MNT-19 pin, regenerated for v27: the support tables are in it and a new database equals it exactly."""
        pin = json.loads((Path(__file__).parent / "fixtures" / "schema_pin.json").read_text())
        with tempfile.TemporaryDirectory() as folder:
            fresh = Path(folder) / "fresh.sqlite3"
            Store(fresh).close()
            self.assertEqual(schema(fresh), pin["fresh"])
        for table in SUPPORT_TABLES:
            self.assertTrue(any(sql.startswith(f"CREATE TABLE {table} ") or sql.startswith(f"CREATE TABLE {table}(") for sql in pin["fresh"]), table)

    def test_one_mission_per_member_and_operation_in_the_schema(self):
        store = Store()
        self.addCleanup(store.close)
        sql = store.one("SELECT sql FROM sqlite_master WHERE name='vault_support_missions'")["sql"].replace(" ", "").replace("\n", "").upper()
        self.assertIn("UNIQUE(OPERATION_ID,USER_ID)", sql)

    def test_support_rows_are_tied_to_their_guild_and_parent(self):
        store = Store()
        self.addCleanup(store.close)
        for table, parent in (("vault_support_missions", "vault_operations"), ("vault_support_attempts", "vault_support_missions")):
            self.assertIn("guild_id", {r[1] for r in store.all(f"PRAGMA table_info({table})")}, table)
            self.assertIn(parent, [r["table"] for r in store.all(f"PRAGMA foreign_key_list({table})")], table)


if __name__ == "__main__":
    unittest.main()
