"""FEAT-66 phase A: schema v26 (vault operation tables) upgrades a v25 file in place, decision D43. Written before the implementation.

CONTRACT: user_version becomes 26; a v25 file is backed up first as ``<file>.pre-v26-<ns>.sqlite3`` (label = the version being upgraded TO, as
v25 used ``pre-v25`` for a v24 file); the new tables are created with ``CREATE TABLE IF NOT EXISTS`` (additive, nothing existing is altered or dropped);
a fresh store and an upgraded file have the same schema, and both equal tests/fixtures/schema_pin.json (regenerated by the implementer, including
the legacy v5 entry). Tables: see tests/test_vault_operation_store.py (OPERATION_TABLES).
"""
import json
import sqlite3
import tempfile
import unittest
from contextlib import closing
from pathlib import Path

from llmcord_core.store import Store

G, CH, ALICE = 1, 100, 5
NOW = 1_760_529_600.0
OPERATION_TABLES = ("vault_operation_claims", "vault_operation_clues", "vault_operation_actions", "vault_operation_stages",
                    "vault_operation_participants", "vault_operations", "vault_operation_settings")


def tables(path):
    with closing(sqlite3.connect(path)) as db:
        return {r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}


def schema(path):
    with closing(sqlite3.connect(path)) as db:
        return sorted(r[0] for r in db.execute("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL"))


def v25_file(folder):
    """A current store with the v26 tables removed again and user_version set back to 25, holding a balance and an active personal vault."""
    path = Path(folder) / "v25.sqlite3"
    store = Store(path)
    w = store.create_space(G, "W", "world")
    a = store.create_character(G, w, "Ann")
    store.bind_channel(G, CH, w)
    store.set_cast(CH, None, [a])
    store.change_balance(G, ALICE, 120, "start", 1)
    store.set_vault_settings(G, enabled=True, reward=30)
    view = store.open_personal_vault(G, ALICE, CH, now=NOW, seed="v25")
    secret = store.one("SELECT secret FROM vault_sessions WHERE id=?", (view["id"],))["secret"]
    store.close()
    with closing(sqlite3.connect(path)) as db, db:
        for table in OPERATION_TABLES:
            db.execute(f"DROP TABLE IF EXISTS {table}")
        db.execute("PRAGMA user_version=25")
    return path, view["id"], secret


class V25UpgradeTests(unittest.TestCase):
    def test_upgrade_adds_the_tables_with_a_pre_v26_backup_and_keeps_rows(self):
        with tempfile.TemporaryDirectory() as folder:
            path, sid, secret = v25_file(folder)
            self.assertFalse(set(OPERATION_TABLES) & tables(path))
            store = Store(path)
            try:
                self.assertEqual(store.one("PRAGMA user_version")[0], 27)
                self.assertEqual(store.balance(G, ALICE), 120)
                self.assertEqual(store.vault_settings(G)["reward"], 30)
                self.assertEqual(store.vault_session(G, ALICE, sid, now=NOW + 5)["status"], "active")
                self.assertEqual(store.one("SELECT secret FROM vault_sessions WHERE id=?", (sid,))["secret"], secret)
                self.assertEqual(store.all("SELECT 1 FROM vault_operations"), [])
                self.assertEqual(store.vault_operation_settings(G)["enabled"], False)
            finally:
                store.close()
            self.assertTrue(set(OPERATION_TABLES) <= tables(path))
            backups = list(Path(folder).glob("v25.sqlite3.pre-v26-*.sqlite3"))
            self.assertEqual(len(backups), 1)
            with closing(sqlite3.connect(backups[0])) as old:
                self.assertEqual(old.execute("PRAGMA user_version").fetchone()[0], 25)
            self.assertFalse(set(OPERATION_TABLES) & tables(backups[0]))

    def test_upgrade_is_idempotent_and_makes_one_backup(self):
        with tempfile.TemporaryDirectory() as folder:
            path, _, _ = v25_file(folder)
            Store(path).close()
            Store(path).close()
            self.assertEqual(len(list(Path(folder).glob("*.pre-v26-*.sqlite3"))), 1)

    def test_a_current_file_is_not_backed_up_again(self):
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "now.sqlite3"
            Store(path).close()
            Store(path).close()
            self.assertEqual(list(Path(folder).glob("*.pre-*.sqlite3")), [])

    def test_older_files_still_get_one_backup_labelled_for_their_own_step(self):
        """A v24 file is backed up once, before anything changes, and still ends at v26 (the old label is not rewritten)."""
        with tempfile.TemporaryDirectory() as folder:
            path, _, _ = v25_file(folder)
            with closing(sqlite3.connect(path)) as db, db:
                for table in ("vault_reward_claims", "vault_actions", "vault_clues", "vault_stages", "vault_sessions", "vault_settings", "vault_advice", "vault_tool_uses"):
                    db.execute(f"DROP TABLE IF EXISTS {table}")
                db.execute("PRAGMA user_version=24")
            Store(path).close()
            backups = list(Path(folder).glob("*.pre-*.sqlite3"))
            self.assertEqual(len(backups), 1)
            self.assertIn(".pre-v25-", backups[0].name)
            self.assertEqual(sqlite3.connect(path).execute("PRAGMA user_version").fetchone()[0], 27)

    def test_a_failed_upgrade_leaves_the_v25_file_as_it_was(self):
        """The upgrade is one transaction: a statement that fails halfway rolls the whole upgrade back (the existing atomic-upgrade guarantee)."""
        from unittest import mock
        with tempfile.TemporaryDirectory() as folder:
            path, _, _ = v25_file(folder)
            before = schema(path)
            with mock.patch.object(Store, "migrate_admin", side_effect=RuntimeError("boom")), self.assertRaises(RuntimeError):
                Store(path)
            self.assertEqual(sqlite3.connect(path).execute("PRAGMA user_version").fetchone()[0], 25)
            self.assertEqual(schema(path), before)

    def test_a_newer_file_is_still_refused(self):
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / "new.sqlite3"
            with closing(sqlite3.connect(path)) as db, db:
                db.execute("PRAGMA user_version=28")
            with self.assertRaisesRegex(ValueError, "newer than this application"):
                Store(path)
            self.assertEqual(list(Path(folder).glob("*.pre-*.sqlite3")), [])


class SchemaTests(unittest.TestCase):
    def test_fresh_store_is_v26_with_every_operation_table(self):
        store = Store()
        self.addCleanup(store.close)
        self.assertEqual(store.one("PRAGMA user_version")[0], 27)
        have = {r[0] for r in store.all("SELECT name FROM sqlite_master WHERE type='table'")}
        self.assertTrue(set(OPERATION_TABLES) <= have)

    def test_upgraded_file_has_the_fresh_operation_schema(self):
        with tempfile.TemporaryDirectory() as folder:
            path, _, _ = v25_file(folder)
            Store(path).close()
            fresh = Path(folder) / "fresh.sqlite3"
            Store(fresh).close()
            self.assertEqual(schema(path), schema(fresh))

    def test_fresh_schema_equals_the_pin(self):
        """MNT-19 pin, regenerated for v26: the operation tables are in it and a new database equals it exactly."""
        pin = json.loads((Path(__file__).parent / "fixtures" / "schema_pin.json").read_text())
        with tempfile.TemporaryDirectory() as folder:
            fresh = Path(folder) / "fresh.sqlite3"
            Store(fresh).close()
            self.assertEqual(schema(fresh), pin["fresh"])
        for table in OPERATION_TABLES:
            self.assertTrue(any(sql.startswith(f"CREATE TABLE {table} ") or sql.startswith(f"CREATE TABLE {table}(") for sql in pin["fresh"]), table)

    def test_claims_are_unique_per_operation_member_and_type_in_the_schema(self):
        store = Store()
        self.addCleanup(store.close)
        sql = store.one("SELECT sql FROM sqlite_master WHERE name='vault_operation_claims'")["sql"].replace(" ", "").replace("\n", "").upper()
        self.assertIn("UNIQUE(OPERATION_ID,USER_ID,TYPE)", sql)

    def test_operation_rows_are_tied_to_their_operation_and_guild(self):
        store = Store()
        self.addCleanup(store.close)
        for table in ("vault_operation_participants", "vault_operation_stages", "vault_operation_actions", "vault_operation_clues", "vault_operation_claims"):
            columns = {r[1] for r in store.all(f"PRAGMA table_info({table})")}
            self.assertTrue({"guild_id", "operation_id"} <= columns, table)
            keys = [r["table"] for r in store.all(f"PRAGMA foreign_key_list({table})")]
            self.assertIn("vault_operations", keys, table)
        self.assertTrue({"guild_id", "channel_id", "week_key", "starts_at", "expires_at", "status", "npc_ids_json"} <= {r[1] for r in store.all("PRAGMA table_info(vault_operations)")})


if __name__ == "__main__":
    unittest.main()
